"""Export frozen numeric parameters, not an external recognition runtime."""
import argparse
import json
from pathlib import Path
import numpy as np
from native_chord_model import TYPES, DEGREES
from prepare import digest

def export(path,destination):
    m=json.loads(path.read_text());gaussian='weights' not in m
    if gaussian:
        mu=np.array(m['means']);precision=np.array(m['precision']);w=mu@precision
        w=np.column_stack([w,-.5*np.sum(w*mu,axis=1)+m['prior']])
    else:w=np.array(m['weights']);precision=np.zeros((48,48))
    def numbers(x):return ','.join(format(float(v),'.17g') for v in x)
    text=['#pragma once','#include <array>',
          '// Generated by tools/real_audio/export_native_chord_model.py.',
          '// Training: 90 GuitarSet microphone recordings, credited in docs/47-native-chord-engine.md.',
          '// Source model SHA256: '+digest(path),'namespace app::guitar::model {',
          'struct Type { const char* suffix; int triad; };',
          'inline constexpr std::array<Type,'+str(len(TYPES))+'> types{{']
    for q,b in TYPES:
        triad=0 if q in ('maj','7','maj7','maj6') else 12 if q in ('min','min7','min6') else -1
        text.append('{"'+q+('/'+DEGREES[b] if b else '')+'",'+str(triad)+'},')
    text+=['}};',f'inline constexpr bool gaussian = {str(gaussian).lower()};',
           f'inline constexpr bool anchored = {str(m.get("anchored",False)).lower()};',
           f'inline constexpr double baseStay = {m.get("baseStay",.9):.17g};',
           f'inline constexpr double detailPenalty = {m.get("detailPenalty",0):.17g};',
           f'inline constexpr double switchCost = {m["switch"]};',
           'inline constexpr std::array<double,2304> precision{'+numbers(precision.ravel())+'};',
           'inline constexpr std::array<std::array<double,49>,'+str(len(TYPES))+'> weights{{']
    text+=['{'+numbers(row)+'},' for row in w]
    text+=['}};','} // namespace app::guitar::model','']
    destination.write_text('\n'.join(text))

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('model',type=Path);p.add_argument('destination',type=Path);a=p.parse_args();export(a.model,a.destination)
