"""Read-only import of the authored six-string chord shapes; never run in f3."""
import hashlib
import json
from pathlib import Path
import os
import re

# Path to a local guitar-tutor (f3) checkout: env F3_GUITAR_TUTOR, default ../guitar-tutor.
source = Path(os.environ.get("F3_GUITAR_TUTOR", "../guitar-tutor")) / "features/chords/data/chords.ts"
project = Path(__file__).resolve().parents[2]
text = source.read_text(encoding="utf-8")
pattern = r"\{ name: '([^']+)', type: '[^']+', strings: \[([^\]]+)\], fingers: \[([^\]]+)\] \}"
chords = []
for name, strings, fingers in re.findall(pattern, text):
    frets = [int(x.strip()) for x in strings.split(",")]
    digits = [int(x.strip()) for x in fingers.split(",")]
    if len(frets) != 6 or len(digits) != 6 or not all(-1 <= x <= 24 for x in frets) or not all(0 <= x <= 4 for x in digits):
        raise ValueError(name)
    chords.append("  {" + json.dumps(name) + ", {" + ", ".join(map(str, frets)) + "}, {" + ", ".join(map(str, digits)) + "}},")
if len(chords) != text.count("{ name:"):
    raise ValueError("Not every authored shape was imported")
header = '''#pragma once
// Chord shape data adapted from StandardTune. See third_party/standardtune/LICENSE.
// Generated by tools/real_audio/import_f3_chords.py; standard guitar tuning only.
#include <array>
namespace app::tuner {
struct Shape { const char* name; std::array<int, 6> frets, fingers; };
inline constexpr Shape shapes[] = {
'''
(project / "app/chord_shapes.h").write_text(header + "\n".join(chords) + "\n};\n}\n", encoding="utf-8")
print(f"Imported {len(chords)} shapes. Source SHA-256 {hashlib.sha256(source.read_bytes()).hexdigest()}")
